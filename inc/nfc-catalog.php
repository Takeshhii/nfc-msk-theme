/**
 * Минимальная цена за штуку (тираж 2000) — для «от … руб/шт» на карточках.
 * Возвращает int или null (если individual / нет тиров).
 */
function nfc_item_min_price( $item ) {
	if ( ! empty( $item['individual'] ) || empty( $item['tiers'] ) ) {
		return null;
	}
	return (int) min( $item['tiers'] );
}

/**
 * URL страницы товара.
 * Большинство товаров живут по «плоскому» адресу /{slug}/ (без /catalog/).
 * Исключения ниже отдаются с иерархией /catalog/{slug}/ — поменяйте массив,
 * если решите сделать все адреса одинаковыми.
 */
function nfc_product_url( $slug ) {
	return '/' . $slug . '/';
}

/** URL страницы готового решения — /resheniya-gotovye-{slug}/ (плоский адрес). */
function nfc_solution_url( $slug ) {
	return '/resheniya-gotovye-' . $slug . '/';
}

/** URL витрины всех решений. */
function nfc_solutions_url() {
	return '/vse-resheniya/';
}

/**
 * ПЕРЕЛИНКОВКА: связанные позиции ДРУГОЙ группы.
 * Для товара — подходящие готовые решения; для решения — подходящие носители.
 * Улучшает внутреннюю перелинковку и помогает пользователю и SEO.
 *
 * @param string $group 'product' | 'solution'
 * @param string $slug  slug текущей страницы
 * @return array<int,array{label:string,url:string}>
 */
function nfc_related_cross( $group, $slug ) {
	// Товар → подходящие решения.
	$prod_to_sol = array(
		'vizitki'   => array( 'vizitka', 'dostup' ),
		'karty'     => array( 'loyalnost', 'dostup', 'vizitka' ),
		'stikery'   => array( 'otzyvy', 'menu', 'wi-fi', 'chayevye' ),
		'breloki'   => array( 'dostup', 'vizitka' ),
		'braslety'  => array( 'dostup', 'loyalnost' ),
		'bejdzhi'   => array( 'vizitka', 'dostup' ),
		'tablichki' => array( 'otzyvy', 'menu', 'wi-fi', 'chayevye' ),
			'pamyatniki' => array( 'pamyat' ),
	);
	// Решение → подходящие носители.
	$sol_to_prod = array(
		'otzyvy'    => array( 'tablichki', 'stikery', 'karty' ),
		'menu'      => array( 'tablichki', 'stikery' ),
		'vizitka'   => array( 'vizitki', 'karty', 'bejdzhi' ),
		'wi-fi'     => array( 'tablichki', 'stikery' ),
		'chayevye'  => array( 'tablichki', 'stikery', 'karty' ),
		'loyalnost' => array( 'karty', 'braslety' ),
		'dostup'    => array( 'karty', 'breloki', 'braslety', 'bejdzhi' ),
			'pamyat'    => array( 'pamyatniki' ),
		'drugoe'    => array( 'vizitki', 'karty', 'stikery', 'tablichki' ),
	);

	$out = array();
	if ( 'solution' === $group ) {
		$items = nfc_catalog_items();
		$slugs = isset( $sol_to_prod[ $slug ] ) ? $sol_to_prod[ $slug ] : array();
		foreach ( $slugs as $s ) {
			if ( isset( $items[ $s ] ) ) {
				$out[] = array( 'label' => $items[ $s ]['title'], 'url' => nfc_product_url( $s ) );
			}
		}
	} else {
		$items = nfc_solution_items();
		$slugs = isset( $prod_to_sol[ $slug ] ) ? $prod_to_sol[ $slug ] : array();
		foreach ( $slugs as $s ) {
			if ( isset( $items[ $s ] ) ) {
				$out[] = array( 'label' => $items[ $s ]['title'], 'url' => nfc_solution_url( $s ) );
			}
		}
	}
	return $out;
}

/**
 * Вернуть данные позиции по группе и slug.
 *
 * @param string $group 'product' | 'solution'
 * @param string $slug  slug страницы
 */
function nfc_item_get( $group, $slug ) {
	$items = ( 'solution' === $group ) ? nfc_solution_items() : nfc_catalog_items();
	return isset( $items[ $slug ] ) ? $items[ $slug ] : array();
}
